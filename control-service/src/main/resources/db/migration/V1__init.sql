-- Schema v1 (T-03): the tables Sprint 1 needs. Later stories add their own migrations
-- (runs and metrics in S2, targets and audit log in S3, tokens, baselines and rules in S4).
-- V1 may still be edited until the first deployment to the Azure VM (ADR-0003); never after that.

-- Users and roles (US-23). Accounts are soft-deleted (GDPR: deletable, while their runs keep a valid
-- reference), so a login is unique only among accounts that are not deleted.
-- password_hash must carry a DelegatingPasswordEncoder prefix of a salted algorithm (NFR-05), so a
-- plain-text or unsalted value can never be stored, even by mistake.
CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         varchar(64)  NOT NULL CHECK (btrim(login) <> ''),
    email         varchar(254),
    password_hash varchar(255) NOT NULL CHECK (password_hash ~ '^\{(bcrypt|argon2[^}]*)\}.+'),
    role          varchar(16)  NOT NULL CHECK (role IN ('ADMIN', 'DEVELOPER', 'VIEWER')),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    deleted_at    timestamptz
);

CREATE UNIQUE INDEX users_login_uq ON users (lower(login)) WHERE deleted_at IS NULL;

-- Scenarios (US-01). Name and description may change; the scripts live in immutable versions.
-- Names are unique ignoring case, so a name always means one scenario in lists, history and CI.
CREATE TABLE scenarios (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200)  NOT NULL CHECK (btrim(name) <> ''),
    description varchar(2000),
    created_by  bigint        NOT NULL REFERENCES users (id),
    created_at  timestamptz   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX scenarios_name_uq ON scenarios (lower(name));
CREATE INDEX scenarios_created_by_idx ON scenarios (created_by);

-- Scenario versions (US-02): numbered 1, 2, ... per scenario and never changed or deleted.
-- sha256 is the hex digest of the script; it is not unique, because going back to an earlier
-- script is a legitimate new version (US-02 compares only with the latest version).
CREATE TABLE scenario_versions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id bigint      NOT NULL REFERENCES scenarios (id),
    version     integer     NOT NULL CHECK (version >= 1),
    script      text        NOT NULL CHECK (script <> '' AND octet_length(script) <= 1048576),
    sha256      varchar(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    created_by  bigint      NOT NULL REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT scenario_versions_scenario_version_uq UNIQUE (scenario_id, version)
);

CREATE INDEX scenario_versions_created_by_idx ON scenario_versions (created_by);

-- Immutability is enforced by the database itself, not only by the application (CLAUDE.md rule).
CREATE FUNCTION reject_scenario_version_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'scenario versions are immutable (% is not allowed)', TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER scenario_versions_immutable
    BEFORE UPDATE OR DELETE ON scenario_versions
    FOR EACH ROW EXECUTE FUNCTION reject_scenario_version_change();

CREATE TRIGGER scenario_versions_no_truncate
    BEFORE TRUNCATE ON scenario_versions
    FOR EACH STATEMENT EXECUTE FUNCTION reject_scenario_version_change();

-- Workers (US-06). A worker that registers again under the same name reuses its record.
-- Only a hash of the per-worker secret is stored; the secret itself is returned once on registration.
CREATE TABLE workers (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(100)     NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    status            varchar(16)      NOT NULL CHECK (status IN ('ONLINE', 'BUSY', 'LOST', 'OFFLINE')),
    cpus              double precision NOT NULL CHECK (cpus > 0),
    mem_mb            integer          NOT NULL CHECK (mem_mb > 0),
    version           varchar(64)      NOT NULL,
    secret_hash       varchar(255)     NOT NULL,
    last_heartbeat_at timestamptz      NOT NULL,
    registered_at     timestamptz      NOT NULL DEFAULT now()
);

CREATE INDEX workers_status_idx ON workers (status);

-- Platform settings edited by ADMIN (US-22). Values are text; the code that reads a key parses it.
CREATE TABLE settings (
    key        varchar(64)  PRIMARY KEY,
    value      varchar(255) NOT NULL,
    updated_at timestamptz  NOT NULL DEFAULT now(),
    updated_by bigint       REFERENCES users (id)
);

CREATE INDEX settings_updated_by_idx ON settings (updated_by);

